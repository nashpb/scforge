'use strict'
const fs = require('fs')
const path = require('path')

const eolOf = text => (text.includes('\r\n') ? '\r\n' : '\n')

function parseFrontmatter(text) {
  const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(text)
  if (!m) throw new Error('agent template has no frontmatter')
  const fm = m[1].split('\n').map(line => {
    const i = line.indexOf(':')
    return [line.slice(0, i).trim(), line.slice(i + 1).trim()]
  })
  return { fm, body: m[2] }
}

function renderAgent(template, role, cfg, name) {
  const { fm, body } = parseFrontmatter(template)
  const set = (k, v) => {
    const e = fm.find(x => x[0] === k)
    if (e) e[1] = v
    else fm.push([k, v])
  }
  set('name', `${name}-${role}`)
  if (cfg.model) set('model', cfg.model)
  if (cfg.effort) set('effort', cfg.effort)
  if (cfg.tools && cfg.tools.length) set('tools', cfg.tools.join(', '))
  if (cfg.skills && cfg.skills.length) set('skills', `[${cfg.skills.join(', ')}]`)
  if (cfg.compact && cfg.compact.window) set('autoCompactWindow', String(cfg.compact.window))
  const head = fm.map(([k, v]) => `${k}: ${v}`).join('\n')
  return `---\n${head}\n---\n\n<!-- generated by ${name}; edit .${name}/config.json, not this file -->\n${body.replace(/^\n+/, '')}`
}

function factoryText(name) {
  return [
    '# Factory rules',
    '',
    `Run rounds through the \`nashworks\` skill. Active settings: \`.${name}/config.json\`. Resume and next steps: \`.${name}/NEXT.md\`.`,
    'A round is planner, red test, sde, code gates, judge. Nothing is done without command output as evidence. Never push.',
    '',
  ].join('\n')
}

function applyBlock(text, name, content) {
  const start = `<!-- ${name}:start -->`
  const end = `<!-- ${name}:end -->`
  const eol = eolOf(text)
  const si = text.indexOf(start)
  const ei = text.indexOf(end)
  const has = si !== -1 && ei > si
  if (content === null) {
    if (!has) return text
    const before = text.slice(0, si).replace(/(\r?\n){2,}$/, eol)
    const after = text.slice(ei + end.length).replace(/^\r?\n/, '')
    return before + after
  }
  const block = `${start}${eol}${content}${eol}${end}`
  if (has) return text.slice(0, si) + block + text.slice(ei + end.length)
  if (text === '') return block + eol
  return text + (text.endsWith(eol) ? eol : eol + eol) + block + eol
}

function setPath(obj, dotted, value) {
  const keys = dotted.split('.')
  const last = keys.pop()
  let n = obj
  for (const k of keys) n = typeof n[k] === 'object' && n[k] !== null ? n[k] : (n[k] = {})
  n[last] = value
}

function delPath(obj, dotted) {
  const keys = dotted.split('.')
  const trail = [obj]
  for (const k of keys.slice(0, -1)) {
    if (typeof trail[trail.length - 1][k] !== 'object' || trail[trail.length - 1][k] === null) return
    trail.push(trail[trail.length - 1][k])
  }
  delete trail[trail.length - 1][keys[keys.length - 1]]
  for (let i = trail.length - 1; i > 0; i--) {
    if (Object.keys(trail[i]).length === 0) delete trail[i - 1][keys[i - 1]]
    else break
  }
}

function desiredState(config, pluginDir, warnings) {
  const name = config.name
  const files = new Map()
  for (const role of Object.keys(config.roles).sort()) {
    const r = config.roles[role]
    if (!r.enabled) continue
    const tpl = path.join(pluginDir, 'agents', `${role}.md`)
    if (!fs.existsSync(tpl)) {
      warnings.push(`no template for role ${role}, skipped`)
      continue
    }
    const text = fs.readFileSync(tpl, 'utf8').replace(/\r\n/g, '\n')
    files.set(`.claude/agents/${name}-${role}.md`, renderAgent(text, role, r, name))
  }
  files.set(`.${name}/CLAUDE.factory.md`, factoryText(name))

  const json = {}
  const settings = config.git.track_factory ? '.claude/settings.json' : '.claude/settings.local.json'
  if (config.compact.enabled && config.compact.strategy === 'auto') {
    json[settings] = { 'env.CLAUDE_AUTOCOMPACT_PCT_OVERRIDE': String(config.compact.threshold_pct) }
  }
  const block = config.claude_md.enabled
    ? { path: config.claude_md.target, content: `@.${name}/CLAUDE.factory.md` }
    : null
  const line = config.git.track_factory ? null : { path: '.gitignore', line: `.${name}/` }
  return { files, json, block, line }
}

function readManifest(file) {
  if (!fs.existsSync(file)) return []
  return JSON.parse(fs.readFileSync(file, 'utf8')).entries
}

// Brings the project in line with `desired`, touching only what the previous manifest owns.
// An empty `desired` is an uninstall.
function reconcile(root, name, desired, dryRun) {
  const abs = p => path.join(root, p)
  const manifestRel = `.${name}/generated.json`
  const actions = []
  const io = {
    read: p => (fs.existsSync(abs(p)) ? fs.readFileSync(abs(p), 'utf8') : null),
    write(p, text) {
      actions.push(`write ${p}`)
      if (dryRun) return
      fs.mkdirSync(path.dirname(abs(p)), { recursive: true })
      fs.writeFileSync(abs(p), text)
    },
    remove(p) {
      actions.push(`remove ${p}`)
      if (!dryRun) fs.rmSync(abs(p), { force: true })
    },
  }
  const prev = readManifest(abs(manifestRel))
  const entries = []

  const owned = new Set(prev.filter(e => e.kind === 'file').map(e => e.path))
  for (const [p, text] of desired.files) {
    const cur = io.read(p)
    if (cur !== null && !owned.has(p) && cur !== text) {
      throw new Error(`${p} exists and was not generated by ${name}; refusing to overwrite`)
    }
  }
  for (const [p, text] of desired.files) {
    if (io.read(p) !== text) io.write(p, text)
    entries.push({ path: p, kind: 'file' })
  }
  for (const p of owned) if (!desired.files.has(p)) io.remove(p)

  const jsonPaths = new Set([
    ...prev.filter(e => e.kind === 'json-keys').map(e => e.path),
    ...Object.keys(desired.json),
  ])
  for (const p of jsonPaths) {
    const old = prev.find(e => e.kind === 'json-keys' && e.path === p)
    const cur = io.read(p)
    let obj = {}
    if (cur !== null) {
      try { obj = JSON.parse(cur) } catch { throw new Error(`${p} is not valid JSON; fix it first`) }
    }
    const before = JSON.stringify(obj)
    const created = old ? old.created : cur === null
    const set = desired.json[p] || {}
    for (const k of old ? old.keys : []) if (!(k in set)) delPath(obj, k)
    for (const [k, v] of Object.entries(set)) setPath(obj, k, v)
    if (Object.keys(set).length) entries.push({ path: p, kind: 'json-keys', keys: Object.keys(set).sort(), created })
    if (created && Object.keys(obj).length === 0) {
      if (cur !== null) io.remove(p)
    } else if (cur === null || JSON.stringify(obj) !== before) {
      io.write(p, JSON.stringify(obj, null, 2) + '\n')
    }
  }

  const prevBlock = prev.find(e => e.kind === 'block')
  const blockPaths = new Set([prevBlock && prevBlock.path, desired.block && desired.block.path].filter(Boolean))
  for (const p of blockPaths) {
    const cur = io.read(p)
    const created = prevBlock && prevBlock.path === p ? prevBlock.created : cur === null
    const content = desired.block && desired.block.path === p ? desired.block.content : null
    const next = applyBlock(cur === null ? '' : cur, name, content)
    if (content !== null) entries.push({ path: p, kind: 'block', created })
    if (created && next.trim() === '') {
      if (cur !== null) io.remove(p)
    } else if (next !== (cur === null ? '' : cur)) {
      io.write(p, next)
    }
  }

  const prevLine = prev.find(e => e.kind === 'line')
  const linePaths = new Set([prevLine && prevLine.path, desired.line && desired.line.path].filter(Boolean))
  for (const p of linePaths) {
    const cur = io.read(p)
    const eol = eolOf(cur || '')
    const had = prevLine && prevLine.path === p ? prevLine : null
    const want = desired.line && desired.line.path === p ? desired.line.line : null
    const created = had ? had.created : cur === null
    let lines = cur === null ? [] : cur.split(/\r?\n/)
    while (lines.length && lines[lines.length - 1] === '') lines.pop()
    let changed = false
    let added = false
    if (had && had.line !== want && had.added) {
      lines = lines.filter(l => l !== had.line)
      changed = true
    }
    if (want !== null) {
      if (lines.includes(want)) added = had && had.line === want ? had.added : false
      else {
        lines.push(want)
        added = true
        changed = true
      }
      entries.push({ path: p, kind: 'line', line: want, added, created })
    }
    if (created && lines.length === 0) {
      if (cur !== null) io.remove(p)
    } else if (changed) {
      io.write(p, lines.join(eol) + eol)
    }
  }

  entries.sort((a, b) => (a.kind + a.path).localeCompare(b.kind + b.path))
  const manifest = JSON.stringify({ version: 1, name, entries }, null, 2) + '\n'
  if (entries.length) {
    if (io.read(manifestRel) !== manifest) io.write(manifestRel, manifest)
  } else if (io.read(manifestRel) !== null) {
    io.remove(manifestRel)
  }
  return actions
}

function generate(root, config, { pluginDir, dryRun = false }) {
  const warnings = []
  const desired = desiredState(config, pluginDir, warnings)
  const actions = reconcile(root, config.name, desired, dryRun)
  return { actions, warnings }
}

function uninstall(root, name, { dryRun = false } = {}) {
  if (!fs.existsSync(path.join(root, `.${name}`, 'generated.json'))) {
    throw new Error(`.${name}/generated.json not found: nothing to uninstall`)
  }
  const none = { files: new Map(), json: {}, block: null, line: null }
  return { actions: reconcile(root, name, none, dryRun), warnings: [] }
}

module.exports = { generate, uninstall, applyBlock, renderAgent }
